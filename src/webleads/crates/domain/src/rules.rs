//! The two lists that decide whether a website counts.
//!
//! They live here rather than in `sitecheck` because the browser side shows the same
//! words to the operator. One copy, one truth.

/// Hosts that mean "they do not have a website of their own".
///
/// `&[&str]` rather than `Vec<String>`: this never changes at runtime, so it can live
/// in the binary itself with no allocation and no start-up cost.
pub const SOCIAL_HOSTS: &[&str] = &[
    "facebook.com",
    "fb.com",
    "fb.me",
    "m.facebook.com",
    "instagram.com",
    "linkedin.com",
    "tiktok.com",
    "snapchat.com",
    "twitter.com",
    "x.com",
    "youtube.com",
    "youtu.be",
    "linktr.ee",
    "wa.me",
    "api.whatsapp.com",
    "t.me",
    "pinterest.com",
    "vk.com",
    "yelp.com",
    "tripadvisor.com",
];

/// Text that gives away a parked or placeholder page, even when it answers 200.
pub const PARKED_MARKERS: &[&str] = &[
    "domain is for sale",
    "domain for sale",
    "buy this domain",
    "this domain may be for sale",
    "parked domain",
    "domain parking",
    "a domain nev elado",
    "weboldal keszul",
    "coming soon",
    "under construction",
    // The same two things said the way the Gulf says them. Without these a parked
    // page in Dubai is judged a working site and the lead is thrown away, which is
    // the expensive direction to be wrong in.
    "website under construction",
    "site is under maintenance",
    "under maintenance",
    "launching soon",
    "default web site page",
    "it works!",
    "welcome to nginx",
    "apache2 ubuntu default page",
];

/// What the known robot checks leave in the page they show instead of the site.
///
/// A page like this means somebody pays for protection in front of a site that is up
/// — it is the opposite of a broken website, whatever the status says. Each is a
/// fingerprint only that checker writes, never a word a real shop page would use.
pub const BOT_CHECK_MARKERS: &[&str] = &[
    // Cloudflare: its challenge script, its option block and its older check.
    "/cdn-cgi/challenge-platform/",
    "_cf_chl_opt",
    "cf-browser-verification",
    // DDoS-Guard.
    "ddos-guard",
    // Sucuri's firewall.
    "sucuri website firewall",
    "sucuri_cloudproxy",
    // Imperva / Incapsula.
    "_incapsula_resource",
    "incapsula incident id",
    // Akamai's refusal page.
    "errors.edgesuite.net",
    // AWS WAF.
    "awswaf",
    // DataDome and HUMAN (PerimeterX).
    "captcha-delivery.com",
    "px-captcha",
    // Vercel's checkpoint and Wordfence on WordPress.
    "vercel security checkpoint",
    "generated by wordfence",
];

/// Is this host one of the social networks, or a subdomain of one?
///
/// Takes `&str` and returns `bool` — no allocation anywhere. `strip_prefix` returns an
/// `Option`, and `unwrap_or(host)` means "use the stripped version if there was a
/// `www.`, otherwise the original".
pub fn is_social_host(host: &str) -> bool {
    let host = host.trim().to_lowercase();
    let host = host.strip_prefix("www.").unwrap_or(&host);
    SOCIAL_HOSTS
        .iter()
        .any(|s| host == *s || host.ends_with(&format!(".{s}")))
}

/// Does this page body read like a parked domain?
pub fn looks_parked(body: &str) -> bool {
    let lowered = body.to_lowercase();
    PARKED_MARKERS.iter().any(|m| lowered.contains(m))
}

/// Is this page a robot check standing in front of the site, rather than the site?
pub fn looks_like_bot_check(body: &str) -> bool {
    let lowered = body.to_lowercase();
    BOT_CHECK_MARKERS.iter().any(|m| lowered.contains(m))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_cloudflare_challenge_is_recognised() {
        let page = r#"<!DOCTYPE html><html><head><title>Just a moment...</title></head>
            <body><noscript>Enable JavaScript and cookies to continue</noscript>
            <script>window._cf_chl_opt = {cvId: '3'};</script>
            <script src="/cdn-cgi/challenge-platform/h/b/orchestrate/chl_page/v1"></script>
            </body></html>"#;
        assert!(looks_like_bot_check(page));
    }

    #[test]
    fn every_known_checker_is_recognised_whatever_the_capitals() {
        for marker in BOT_CHECK_MARKERS {
            let page = format!("<html><body>{}</body></html>", marker.to_uppercase());
            assert!(looks_like_bot_check(&page), "{marker}");
        }
    }

    #[test]
    fn an_ordinary_shop_page_is_not_a_robot_check() {
        // "Just a moment" alone is something a real page can say.
        let page = "<html><body><h1>Fodrászat</h1><p>Just a moment from the metro.                     Call us to book.</p></body></html>";
        assert!(!looks_like_bot_check(page));
    }

    #[test]
    fn social_hosts_are_recognised_with_or_without_www() {
        assert!(is_social_host("facebook.com"));
        assert!(is_social_host("www.facebook.com"));
        assert!(is_social_host("m.facebook.com"));
        assert!(is_social_host("INSTAGRAM.COM"));
    }

    #[test]
    fn a_real_business_site_is_not_social() {
        assert!(!is_social_host("zugloifodraszat.hu"));
        assert!(!is_social_host("borzasbarber.hu"));
    }

    #[test]
    fn a_lookalike_domain_does_not_count() {
        // The check must be "ends with .facebook.com", not "contains facebook.com",
        // or someone's notfacebook.com would be misread as a social page.
        assert!(!is_social_host("notfacebook.com"));
        assert!(!is_social_host("facebook.com.evil.hu"));
    }

    #[test]
    fn parked_pages_are_spotted_whatever_the_case() {
        assert!(looks_parked("<h1>This Domain Is For Sale</h1>"));
        assert!(looks_parked("Welcome to nginx!"));
        assert!(!looks_parked("<h1>Fodrászat Zugló — nyitva 9-17</h1>"));
    }

    #[test]
    fn a_parked_page_is_spotted_in_the_gulf_wording_too() {
        // Judged a working site, these businesses would be dropped from the list —
        // which is the expensive direction to be wrong in: the whole product is
        // shops that have no site.
        assert!(looks_parked("Our Website Under Construction"));
        assert!(looks_parked("<p>This site is under maintenance</p>"));
        assert!(looks_parked("LAUNCHING SOON"));
    }

    #[test]
    fn a_real_shop_that_mentions_building_work_is_not_parked() {
        // A builder's own website talks about construction all day. The markers are
        // phrases, not words, for exactly this reason.
        assert!(!looks_parked(
            "<h1>Al Quoz Construction LLC</h1><p>Steel fabrication since 1998</p>"
        ));
        assert!(!looks_parked(
            "We are open. Maintenance contracts available."
        ));
    }
}
